"""Evidence pack + audit trail.

The audit trail is generated by Python from the actual run, step by step, with the numbers each step produced.
It is the non-negotiable record of how the answer was reached; Claude's memo is written on top of it.
"""
import numpy as np
import pandas as pd

from .model import pnl


def pnl_inputs_from_research(profile, base=None):
    """Prefill the P&L input table from Claude's research. Rent is left for the scrape / the user."""
    df = (base if base is not None else pnl.empty_inputs()).copy()
    src = ((profile or {}).get("data") or {}).get("pnl_inputs") or {}
    for k, v in src.items():
        if k in df["key"].values and isinstance(v, dict) and v.get("included_in"):
            df.loc[df.key == k, ["low", "mode", "high", "source", "label"]] = [0, 0, 0, f"included in {v['included_in']}", v.get("label") or "third_party_estimate"]
        elif k in df["key"].values and isinstance(v, dict) and v.get("mode") is not None:
            lo, mo, hi = v.get("low") or v["mode"], v["mode"], v.get("high") or v["mode"]
            df.loc[df.key == k, ["low", "mode", "high", "source", "label"]] = [lo, mo, hi, v.get("source") or "", v.get("label") or ""]
    return df


def rent_model(profile):
    rm = (((profile or {}).get("data") or {}).get("rent_model")) or "market_lease"
    return "franchisor_property" if rm == "franchisor_property" else "market_lease"


def _fmt(x, d=0):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:,.{d}f}"


def audit_trail(R, rob=None, pnl_out=None, rents=None, profile=None):
    m, P = R.metrics, R.params
    steps = [
        ("Data", f"Municipal premises census ({m['candidates_vacant']:,} vacant street-level units scored), Padrón by "
                 f"census section (2,462 sections), INE household income 2024, district/barrio boundaries."),
        ("Brand stores", f"Matched {m['stores']} open premises to '{R.brand}' by normalised trade name "
                         f"({len(R.matched_names)} name variants); duplicates <30 m merged."),
        ("Category", f"Brand's own activity licences → code {m['category']}; {m['competitors']:,} open competitors share it."),
        ("Suitability model", f"Logistic regression: {m['stores']} brand stores vs {m['background_n']:,} background premises, "
                              f"7 location features. Spatial cross-validation (districts held out): AUC {_fmt(m['auc_spatial_cv'], 3)} "
                              f"(folds {m['auc_folds']})."),
        ("Strongest drivers", "; ".join(f"{r.feature} ({r.effect:+.2f})" for r in R.coefficients.head(3).itertuples())),
        ("Gate", f"Candidate must score ≥ the bottom-quartile existing store ({m['gate_score']:.3f}) → "
                 f"{m['candidates_pass_gate']:,} units pass."),
        ("Demand calibration", f"Demand = residents + {m['demand_activity_weight']:.0f} × open premises per section; distance decay "
                               f"{m['demand_decay_m']} m. Chosen from {len(R.calibration)} combinations as the one giving existing "
                               f"stores the most even catchments (CV {m['demand_calibration_cv']:.2f})."),
        ("Huff competition model", f"Each section's demand split across the brand's stores, {m['competitors']:,} competitors and an "
                                   f"outside option. A median existing store captures {_fmt(m['median_existing_store_demand'])} demand units."),
        ("Optimiser", f"Greedy selection of the unit adding most incremental demand, re-run after each pick (cannibalisation), "
                      f"≥{P['min_spacing_m']} m apart. Store-count curve: {m['additional_stores_supported']} more stores each capture "
                      f"≥{P['saturation_ratio']:.0%} of a median store."),
    ]
    if rob:
        s = rob["summary"]
        steps.append(("Robustness Monte Carlo", f"{rob['B']} draws (bootstrap of training data × demand parameters from the 5 best "
                      f"calibration cells). Pick stability: " + ", ".join(f"#{int(r['rank'])} {r.p_selected:.0%}" for _, r in s.iterrows())))
    if rents:
        steps.append(("Rent scrape (Apify → Idealista)", "; ".join(
            f"#{k}: {v['stats'].get('n', 0)} listings" + (f", median €{v['stats']['p50']:.1f}/m²/mo" if 'p50' in v['stats'] else "")
            for k, v in rents.items())))
    if profile and profile.get("data"):
        d = profile["data"]
        steps.append(("Franchise research (Claude + web search)",
                      f"Individual franchise in Spain: {d.get('individual_franchise_available_spain')}. "
                      f"{len(profile.get('citations', []))} sources cited."))
    if pnl_out and pnl_out.get("ok"):
        s = pnl_out["summary"]
        steps.append(("P&L Monte Carlo", f"{pnl_out['N']:,} draws per site. Median EBITDA: " + ", ".join(
            f"#{int(r['rank'])} €{r.ebitda_p50:,.0f} (P(loss) {r.p_loss:.0%})" for _, r in s.iterrows())))
    elif pnl_out:
        steps.append(("P&L Monte Carlo", "Not run — missing inputs: " + ", ".join(pnl_out["missing"])))
    return steps


def evidence_pack(R, rob=None, pnl_out=None, rents=None, profile=None):
    cols = ["rank", "address", "barrio", "district", "suitability", "incremental_demand", "vs_median_store",
            "dist_nearest_brand_m", "comp_500", "footfall", "transit_300", "office_500", "food_300", "income_1000", "pop_1000", "young_share_1000"]
    ev = {
        "brand": R.brand,
        "audit_trail": [{"step": a, "detail": b} for a, b in audit_trail(R, rob, pnl_out, rents, profile)],
        "model_metrics": R.metrics, "model_warnings": R.warnings, "parameters": R.params,
        "top_drivers": R.coefficients.round(3).to_dict("records"),
        "sites": R.sites[cols].round(3).to_dict("records"),
        "caveats": [
            "Existing stores come from the municipal census by trade name; stores registered under company names are missed, "
            "which inflates the 'more stores supported' count.",
            "Demand = residents + daytime-activity proxy (open premises); no measured footfall yet.",
            "Distances are straight-line, not walking network.",
            "Candidate sites are vacant units in the census; unit size and availability are unverified unless a listing matches.",
            "P&L assumes revenue scales proportionally with captured demand (elasticity 1), pre-tax, unlevered.",
        ],
    }
    if rob:
        ev["robustness_monte_carlo"] = {"draws": rob["B"], "radius_m": rob["radius_m"],
                                        "per_site": rob["summary"].round(3).to_dict("records"),
                                        "most_picked_alternatives": rob["alternatives"].head(8).reset_index(drop=True)
                                        .assign(address=lambda d: d.street_name.str.title() + " " + d.street_number)
                                        [["address", "times_picked"]].to_dict("records")}
    if pnl_out:
        ev["pnl_monte_carlo"] = ({"draws": pnl_out["N"], "payback_target_yrs": pnl_out["payback_target_yrs"],
                                  "per_site": pnl_out["summary"].round(3).to_dict("records"),
                                  "inputs": pnl_out["inputs"].to_dict("records"),
                                  "top_sensitivities": pnl_out["sensitivity"].assign(a=lambda d: d.spearman.abs())
                                  .sort_values("a", ascending=False).drop(columns="a").head(12).round(3).to_dict("records")}
                                 if pnl_out.get("ok") else {"not_run_missing": pnl_out["missing"]})
    if rents:
        ev["rent_scrape"] = {k: {"stats": v["stats"], "retrieved": v["retrieved"], "radius_km": v["radius_km"]} for k, v in rents.items()}
    if profile:
        ev["franchise_research"] = {"summary": profile.get("summary"), "data": profile.get("data"),
                                    "citations": profile.get("citations")}
    return ev


# ---------------------------------------------------------------- pipeline (money-first) versions
def trail_from_pipeline(O):
    R, K, m = O["R"], O["ranked"], O["R"].metrics
    prof = (O.get("profile") or {}).get("data") or {}
    steps = []
    if prof:
        steps.append(("Franchise research (Claude + web search)",
                      f"Individual franchise in Spain: {prof.get('individual_franchise_available_spain')}. Premises: "
                      f"{O['rent_model'].replace('_', ' ')}. {len((O.get('profile') or {}).get('citations') or [])} sources."))
    else:
        steps.append(("Franchise research", "Not run — ranking falls back to customers per euro of rent."))
    steps += [
        ("Brand stores", f"{m['stores']} open stores found (municipal census + OpenStreetMap, merged within 120 m; offices, "
                         f"warehouses and airport units excluded)."),
        ("Competitors", f"{m['competitors']:,} open premises in the brand's activity class `{m['category']}` or belonging to "
                        "a known chain in that class."),
        ("Location model", f"Logistic regression, {m['stores']} stores vs {m['background_n']:,} background premises, 9 features "
                           f"(residents, income, age, calibrated footfall, offices, metro/rail, food density, competitors). "
                           f"Spatial-CV AUC {_fmt(m['auc_spatial_cv'], 3)} → {m['reliability']}."),
        ("Strongest drivers", "; ".join(f"{r.feature} ({r.effect:+.2f})" for r in R.coefficients.head(3).itertuples())),
        ("Demand model", f"Huff gravity model over 2,462 census sections; demand = residents + {m['demand_activity_weight']:.0f} × "
                         f"consumer & office premises (industrial excluded), decay {m['demand_decay_m']} m, calibrated on the brand's network."),
    ]
    if K.get("ok"):
        lg = K["log"]
        steps.append(("Listings funnel", " → ".join(f"{k.replace('_', ' ')} {v:,}" for k, v in lg.items())))
        steps.append(("Ranking", f"Metric: {K['metric']}. Pool of {K['pool']} best units re-scored after each pick "
                                 f"(cannibalisation). Demand capped at {K['demand_cap']:.2f}× a median store."))
        S = K["sites"]
        if O["econ"]:
            steps.append(("P&L Monte Carlo", "10,000 draws per unit, own rent and traspaso. Median EBITDA: " + ", ".join(
                f"#{int(r['rank'])} €{r.ebitda_p50:,.0f} (P(loss) {r.p_loss:.0%})" for _, r in S.iterrows())))
    return steps


def evidence_from_pipeline(O):
    R, K = O["R"], O["ranked"]
    cols = [c for c in ["rank", "address", "neighbourhood", "m2", "rent_month", "eur_m2", "local_eur_m2", "traspaso_eur",
                        "suitability", "demand_ratio", "dist_nearest_brand_m", "comp_500", "footfall", "transit_300",
                        "office_500", "income_1000", "pop_1000", "revenue_p50", "ebitda_p10", "ebitda_p50", "ebitda_p90",
                        "p_loss", "payback_p50", "p_payback", "invest_p50", "roic_p50", "rent_share", "url"]
            if K.get("ok") and c in K["sites"].columns]
    ev = {
        "brand": R.brand,
        "audit_trail": [{"step": a, "detail": b} for a, b in trail_from_pipeline(O)],
        "model_metrics": R.metrics, "model_warnings": R.warnings,
        "top_drivers": R.coefficients.round(3).to_dict("records"),
        "ranking_metric": K.get("metric"), "listings_funnel": K.get("log"),
        "recommended_units": K["sites"][cols].round(3).to_dict("records") if K.get("ok") else [],
        "brand_economics_used": {k: list(v) for k, v in (O["econ"] or {}).items()},
        "missing_economics": O["missing"], "rent_model": O["rent_model"], "unit_size_range_m2": O["m2_range"],
        "caveats": [
            "Revenue = brand average x demand ratio (capped at the brand's 90th-percentile store) x model-error noise.",
            "Demand ratios come from a gravity model calibrated on the brand's network and on 31 pedestrian counters; "
            "no measured sales per store.",
            "Distances are straight-line, not walking network.",
            "Listings are as advertised on Idealista; condition, licence status and exact frontage are not verified.",
            "EBITDA is pre-tax, before depreciation and financing.",
        ],
    }
    if O.get("profile"):
        ev["franchise_research"] = {"summary": O["profile"].get("summary"), "data": O["profile"].get("data"),
                                    "citations": O["profile"].get("citations")}
    return ev
